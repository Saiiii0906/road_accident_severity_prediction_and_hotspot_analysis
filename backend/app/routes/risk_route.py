"""
Student C - Road Risk Prediction & Analysis API Routes.

Exposes:
- Canonical endpoint: POST /road-risk/predict (and /api/road-risk/predict)
- Compatibility endpoint: POST /risk/assess (and /api/risk/assess)
"""

from typing import Annotated

from fastapi import APIRouter, Depends, status

from app.schemas.risk import (
    RiskAssessmentRequest,
    RiskAssessmentResponse,
    RoadRiskPredictionResponse,
    RoadRiskQueryRequest,
)
from app.services.risk_service import RiskService

router = APIRouter(tags=["Road Risk Prediction"])


def get_risk_service() -> RiskService:
    """Dependency provider for RiskService singleton."""
    return RiskService()


RiskServiceDep = Annotated[RiskService, Depends(get_risk_service)]


@router.post(
    "/road-risk/predict",
    response_model=RoadRiskPredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Query GNN road segment risk predictions",
    description=(
        "Query precomputed topological accident risk predictions generated by "
        "Student C's RoadRiskGNN model. Supports filtering by road number, "
        "spatial bounding box, or spatial center + radius."
    ),
)
def predict_road_risk(
    request: RoadRiskQueryRequest,
    service: RiskServiceDep,
) -> RoadRiskPredictionResponse:
    """Query topological road risk predictions for roads or spatial areas."""
    return service.predict(request)


@router.post(
    "/risk/assess",
    response_model=RiskAssessmentResponse,
    status_code=status.HTTP_200_OK,
    summary="Assess accident risk for a location and condition set",
    description="Legacy endpoint: assess risk for a specific geographic location.",
)
def assess_risk(
    request: RiskAssessmentRequest,
    service: RiskServiceDep,
) -> RiskAssessmentResponse:
    """Assess accident risk for the given location."""
    return service.assess(request)